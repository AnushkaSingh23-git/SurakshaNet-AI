import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export const generatePdf = (analysisResult) => {
  const doc = new jsPDF();

  const caseId =
    "SN-" + new Date().getTime().toString().slice(-8);

  const extractedData = {
    phone:
      analysisResult.phone?.length
        ? analysisResult.phone.join(", ")
        : "Not Found",

    email:
      analysisResult.email?.length
        ? analysisResult.email.join(", ")
        : "Not Found",

    website:
      analysisResult.website?.length
        ? analysisResult.website.join(", ")
        : "Not Found",

    upi:
      analysisResult.upi?.length
        ? analysisResult.upi.join(", ")
        : "Not Found",

    bank:
      analysisResult.bank?.length
        ? analysisResult.bank.join(", ")
        : "Not Found",
  };

  // ===== HEADER =====

  doc.setFillColor(15, 23, 42);

  doc.rect(0, 0, 210, 35, "F");

  doc.setTextColor(255, 255, 255);

  doc.setFontSize(22);

  doc.text("SURAKSHANET AI", 20, 16);

  doc.setFontSize(11);

  doc.text(
    "National Cyber Crime Intelligence Platform",
    20,
    24
  );

  doc.setTextColor(0);

  autoTable(doc, {
    startY: 42,

    head: [["Field", "Value"]],

    body: [
      ["Case ID", caseId],
      [
        "Generated",
        new Date().toLocaleString(),
      ],
      [
        "Officer",
        "AI Investigation Engine",
      ],
      [
        "Risk Level",
        analysisResult.risk,
      ],
      [
        "Risk Score",
        `${analysisResult.score}%`,
      ],
      [
        "Confidence",
        `${analysisResult.confidence}%`,
      ],
      [
        "Scam Type",
        analysisResult.type,
      ],
    ],

    theme: "grid",

    headStyles: {
      fillColor: [220, 38, 38],
      textColor: 255,
    },
  });

  let y = doc.lastAutoTable.finalY + 12;

    // ===== RISK ANALYSIS =====

  doc.setFillColor(255, 245, 245);

  doc.roundedRect(15, y - 5, 180, 42, 3, 3, "F");

  doc.setFontSize(16);

  doc.setTextColor(200, 0, 0);

  doc.text("RISK ANALYSIS", 20, y + 5);

  doc.setTextColor(0);

  doc.setFontSize(12);

  doc.text(
    `Risk Level : ${analysisResult.risk}`,
    25,
    y + 15
  );

  doc.text(
    `Risk Score : ${analysisResult.score}%`,
    25,
    y + 23
  );

  doc.text(
    `Confidence : ${analysisResult.confidence}%`,
    110,
    y + 15
  );

  doc.text(
    `Scam Type : ${analysisResult.type}`,
    110,
    y + 23
  );

  y += 50;

  // ===== EXTRACTED EVIDENCE =====

  autoTable(doc, {

    startY: y,

    head: [["Extracted Evidence", "Value"]],

    body: [

      ["Phone", extractedData.phone],

      ["Email", extractedData.email],

      ["Website", extractedData.website],

      ["UPI ID", extractedData.upi],

      ["Bank", extractedData.bank],

    ],

    theme: "striped",

    headStyles: {

      fillColor: [0, 102, 204],

      textColor: 255,

    },

  });

  y = doc.lastAutoTable.finalY + 12;

    // ===== SUSPICIOUS FINDINGS =====

  doc.setFontSize(16);
  doc.setTextColor(200, 0, 0);
  doc.text("SUSPICIOUS FINDINGS", 20, y);

  y += 10;

  doc.setTextColor(0);

  autoTable(doc, {
    startY: y,
    head: [["Detected Keyword"]],
    body:
      analysisResult.findings?.length > 0
        ? analysisResult.findings.map((item) => [item])
        : [["No suspicious keywords detected"]],
    theme: "grid",
    headStyles: {
      fillColor: [220, 38, 38],
      textColor: 255,
    },
  });

  y = doc.lastAutoTable.finalY + 12;

  // ===== AI EXPLANATION =====

  doc.setFontSize(16);
  doc.setTextColor(0, 102, 204);
  doc.text("AI EXPLANATION", 20, y);

  y += 10;

  autoTable(doc, {
    startY: y,
    body:
      analysisResult.explanation?.map((item) => [item]) || [
        ["No explanation available"],
      ],
    theme: "plain",
  });

  y = doc.lastAutoTable.finalY + 12;

  // ===== RECOMMENDATIONS =====

  doc.setFontSize(16);
  doc.setTextColor(0, 150, 0);
  doc.text("RECOMMENDATIONS", 20, y);

  y += 10;

  autoTable(doc, {
    startY: y,
    body:
      analysisResult.recommendation?.map((item) => [item]) || [
        ["No recommendation available"],
      ],
    theme: "striped",
    headStyles: {
      fillColor: [0, 150, 0],
      textColor: 255,
    },
  });

  y = doc.lastAutoTable.finalY + 15;

    // ===== FOOTER =====

  if (y > 250) {
    doc.addPage();
    y = 30;
  }

  doc.setDrawColor(180);
  doc.line(20, y, 190, y);

  y += 10;

  doc.setFontSize(10);
  doc.setTextColor(120);

  doc.text(
    `Generated on: ${new Date().toLocaleString()}`,
    20,
    y
  );

  y += 7;

  doc.text(
    "Generated by SurakshaNet AI | National Cyber Crime Intelligence Platform",
    20,
    y
  );

  y += 7;

  doc.text(
    "This report is AI-generated and intended for investigation assistance only.",
    20,
    y
  );

  y += 7;

  doc.text(
    "Cyber Helpline: 1930 | https://cybercrime.gov.in",
    20,
    y
  );

  doc.save(`SurakshaNet_Report_${caseId}.pdf`);
};